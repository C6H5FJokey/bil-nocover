import { mkdir, readFile, writeFile, copyFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { commonRules, dynamicRules, searchInputSelectors, renderHideRules, renderPlaceholderRules } from "../src/rules.mjs";
import { startPlaceholderCleaner } from "../src/placeholder-cleaner.mjs";
import { createSearchEngine } from "../src/search-core.mjs";
import { startSearchBridge } from "../src/search-bridge.mjs";
import { startSearchFilter } from "../src/search-filter.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const edge = resolve(root, "dist/edge");
const userscript = resolve(root, "dist/userscript");
const { version } = JSON.parse(await readFile(resolve(root, "package.json"), "utf8"));
const commonCss = `/* Generated by scripts/build.mjs. Edit src/rules.mjs. */\n\n${renderHideRules(commonRules)}\n${renderPlaceholderRules()}`;
const dynamicCss = `/* Generated by scripts/build.mjs. Edit src/rules.mjs. */\n\n${renderHideRules(dynamicRules)}`;
const cleanerCode = `(${startPlaceholderCleaner.toString()})(document, ${JSON.stringify(searchInputSelectors)});`;
const searchCss = await readFile(resolve(root, "src/extension/search.css"), "utf8");
const engineCode = `(${createSearchEngine.toString()})()`;
const bridgeCode = startSearchBridge.toString();
const filterCode = startSearchFilter.toString();
const manifest = JSON.parse(await readFile(resolve(root, "src/extension/manifest.json"), "utf8"));
manifest.version = version;

await mkdir(edge, { recursive: true });
await mkdir(userscript, { recursive: true });
await writeFile(resolve(edge, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(resolve(edge, "common.css"), commonCss);
await writeFile(resolve(edge, "dynamic.css"), dynamicCss);
await writeFile(resolve(edge, "content.js"), `// Generated by scripts/build.mjs.\n(() => {\n"use strict";\n${cleanerCode}\n})();\n`);
for (const filename of ["popup.html", "popup.css", "popup.js", "search.css"]) {
  await copyFile(resolve(root, "src/extension", filename), resolve(edge, filename));
}
const background = (await readFile(resolve(root, "src/extension/background.mjs"), "utf8"))
  .replace('"../guest-rules.mjs"', '"./guest-rules.mjs"');
await writeFile(resolve(edge, "service-worker.js"), background);
await copyFile(resolve(root, "src/guest-rules.mjs"), resolve(edge, "guest-rules.mjs"));
await writeFile(resolve(edge, "search-bridge.js"), `(${bridgeCode})(window);\n`);
await writeFile(resolve(edge, "search-filter.js"), `(${filterCode})(window, ${engineCode}, {
  read: () => chrome.storage.local.get({ searchEnabled: true, hideSearchAds: true }),
  write: patch => chrome.storage.local.set(patch),
  listen: callback => chrome.storage.onChanged.addListener((changes, area) => {
    if (area !== 'local') return;
    const patch = {};
    for (const key of ['searchEnabled', 'hideSearchAds']) {
      if (changes[key]) patch[key] = changes[key].newValue ?? true;
    }
    if (Object.keys(patch).length) callback(patch);
  }),
});\n`);

const metadata = `// ==UserScript==
// @name         Bili NoCover · 免疫推荐
// @namespace    urn:bili-nocover
// @version      ${version}
// @description  隐藏哔哩哔哩推荐、热搜和评论，清除搜索占位词，并提供可恢复的搜索结果筛选。
// @match        *://*.bilibili.com/*
// @run-at       document-start
// @grant        GM_addStyle
// @grant        GM_getValue
// @grant        GM_setValue
// @grant        unsafeWindow
// @sandbox      JavaScript
// @noframes
// ==/UserScript==`;
const script = `${metadata}

// Generated by scripts/build.mjs. Edit src/ instead.
(() => {
  "use strict";
  const commonCss = ${JSON.stringify(commonCss)};
  const dynamicCss = ${JSON.stringify(dynamicCss)};
  GM_addStyle(commonCss + (location.hostname === "t.bilibili.com" ? "\\n" + dynamicCss : ""));
  ${cleanerCode}
  if (location.hostname === "search.bilibili.com") {
    GM_addStyle(${JSON.stringify(searchCss)});
    (${filterCode})(window, ${engineCode}, {
      read: () => ({searchEnabled: GM_getValue('searchEnabled', true), hideSearchAds: GM_getValue('hideSearchAds', true)}),
      write: patch => { for (const [key, value] of Object.entries(patch)) GM_setValue(key, value); },
    });
    (${bridgeCode})(typeof unsafeWindow !== 'undefined' ? unsafeWindow : window);
  }
})();
`;
await writeFile(resolve(userscript, "bili-nocover.user.js"), script);
console.log(`Built Bili NoCover ${version}: dist/edge + dist/userscript`);
