import { mkdir, readFile, writeFile, copyFile } from "node:fs/promises";
import { fileURLToPath } from "node:url";
import { resolve } from "node:path";
import { commonRules, dynamicRules, searchInputSelectors, renderHideRules, renderPlaceholderRules } from "../src/rules.mjs";
import { startPlaceholderCleaner } from "../src/placeholder-cleaner.mjs";

const root = fileURLToPath(new URL("../", import.meta.url));
const edge = resolve(root, "dist/edge");
const userscript = resolve(root, "dist/userscript");
const { version } = JSON.parse(await readFile(resolve(root, "package.json"), "utf8"));
const commonCss = `/* Generated by scripts/build.mjs. Edit src/rules.mjs. */\n\n${renderHideRules(commonRules)}\n${renderPlaceholderRules()}`;
const dynamicCss = `/* Generated by scripts/build.mjs. Edit src/rules.mjs. */\n\n${renderHideRules(dynamicRules)}`;
const cleanerCode = `(${startPlaceholderCleaner.toString()})(document, ${JSON.stringify(searchInputSelectors)});`;
const manifest = JSON.parse(await readFile(resolve(root, "src/extension/manifest.json"), "utf8"));
manifest.version = version;

await mkdir(edge, { recursive: true });
await mkdir(userscript, { recursive: true });
await writeFile(resolve(edge, "manifest.json"), `${JSON.stringify(manifest, null, 2)}\n`);
await writeFile(resolve(edge, "common.css"), commonCss);
await writeFile(resolve(edge, "dynamic.css"), dynamicCss);
await writeFile(resolve(edge, "content.js"), `// Generated by scripts/build.mjs.\n(() => {\n"use strict";\n${cleanerCode}\n})();\n`);
for (const filename of ["popup.html", "popup.css"]) {
  await copyFile(resolve(root, "src/extension", filename), resolve(edge, filename));
}

const metadata = `// ==UserScript==
// @name         Bili NoCover · 免疫推荐
// @namespace    urn:bili-nocover
// @version      ${version}
// @description  隐藏哔哩哔哩推荐、热搜和评论，清除搜索推荐占位词。
// @match        *://*.bilibili.com/*
// @run-at       document-start
// @grant        GM_addStyle
// @sandbox      DOM
// @noframes
// ==/UserScript==`;
const script = `${metadata}

// Generated by scripts/build.mjs. Edit src/ instead.
(() => {
  "use strict";
  const commonCss = ${JSON.stringify(commonCss)};
  const dynamicCss = ${JSON.stringify(dynamicCss)};
  GM_addStyle(commonCss + (location.hostname === "t.bilibili.com" ? "\\n" + dynamicCss : ""));
  ${cleanerCode}
})();
`;
await writeFile(resolve(userscript, "bili-nocover.user.js"), script);
console.log(`Built Bili NoCover ${version}: dist/edge + dist/userscript`);
